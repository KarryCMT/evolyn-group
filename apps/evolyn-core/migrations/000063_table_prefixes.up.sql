-- 000063: 数据库表命名空间前缀标准化（docs/低代码平台/数据库表命名空间前缀调整方案.md 第一阶段）。
-- 以数据所有权与隔离边界统一表名前缀：pf_ 平台 / sys_ 系统 / tn_ 租户；wf_ 流程引擎
-- 11 张表维持独立命名空间不动；schema_migrations 是迁移器私有控制表，保持原名。
-- 纯物理改名：不改 API 契约、权限资源编码与业务语义；历史迁移 000001..000062
-- 保持原样（checksum 校验约束），新库全链执行与本迁移升级两条路径终态一致
-- （MIGRATE-INT-005 指纹比对覆盖表/列/索引/约束名）。
-- 元数据同步对齐：索引、约束（含默认主键 xxx_pkey、内联外键 xxx_yyy_fkey、
-- 内联唯一键 xxx_yyy_key）与 BIGSERIAL 序列名中的旧表名段一并替换为
-- 新表名段，使 pg_dump 级元数据同样遵循新命名；对象功能与关联不受影响。

